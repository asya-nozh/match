</div>
</div>

<h3>1. Общие положения</h3>
<p>Настоящие правила определяют порядок использования веб-приложения «Мэтч», предназначенного для поиска собеседников, общения пользователей и установления новых связей по интересам.</p>
<p>Используя веб-приложение, пользователь подтверждает, что ознакомился с настоящими правилами и обязуется соблюдать их при работе с сервисом.</p>

<h3>2. Назначение веб-приложения</h3>
<p>Веб-приложение «Мэтч» предназначено для регистрации пользователей, заполнения профиля, просмотра анкет других участников, поиска людей по интересам, обмена сообщениями, формирования связей и подачи жалоб при нарушении правил общения.</p>
<p>Сервис не является средством официального трудоустройства, оказания медицинской, юридической или иной профессиональной помощи. Информация, размещаемая пользователями в профилях и сообщениях, носит пользовательский характер.</p>

<h3>3. Регистрация и учетная запись</h3>
<p>Для получения доступа к основным функциям веб-приложения пользователь проходит регистрацию, указывая необходимые данные: имя, никнейм, адрес электронной почты и пароль.</p>
<ul>
<li>Пользователь обязан указывать достоверные данные и не использовать чужие учетные записи.</li>
<li>Пользователь самостоятельно отвечает за сохранность логина и пароля.</li>
<li>Запрещается передавать данные для входа третьим лицам.</li>
<li>При обнаружении подозрительной активности пользователь должен прекратить использование аккаунта и обратиться к администрации сервиса.</li>
</ul>

<h3>4. Профиль пользователя</h3>
<p>Профиль используется для представления пользователя другим участникам веб-приложения. В профиле могут отображаться имя, никнейм, город, цель общения, интересы и фотография пользователя.</p>
<p>Пользователь несет ответственность за информацию, размещенную в своем профиле. Запрещается размещать сведения, нарушающие права других лиц, содержащие оскорбления, угрозы, призывы к противоправным действиям или недостоверную информацию.</p>

<h3>5. Общение между пользователями</h3>
<p>Веб-приложение предоставляет возможность обмениваться текстовыми сообщениями. Пользователь обязуется соблюдать уважительный стиль общения и не нарушать личные границы других участников.</p>
<ul>
<li>Запрещены оскорбления, угрозы, травля и дискриминационные высказывания.</li>
<li>Запрещена массовая рассылка одинаковых сообщений и спам.</li>
<li>Запрещена публикация вредоносных ссылок и попытки получения чужих персональных данных.</li>
<li>Запрещается использовать сервис для мошенничества, давления или введения других пользователей в заблуждение.</li>
</ul>

<h3>6. Жалобы и модерация</h3>
<p>Если пользователь считает, что другой участник нарушает правила сервиса, он может отправить жалобу. Жалоба передается на рассмотрение модератору.</p>
<p>Модератор может проверить профиль пользователя, содержание жалобы и связанные с ней сообщения. По результатам рассмотрения жалобы может быть принято одно из решений: отклонить жалобу, вынести предупреждение, временно ограничить доступ к функциям сервиса или заблокировать учетную запись.</p>

<h3>7. Ограничение доступа</h3>
<p>Администрация веб-приложения вправе ограничить доступ пользователя к отдельным функциям или учетной записи в случае нарушения настоящих правил.</p>
<p>Ограничение может применяться при размещении запрещенного контента, нарушении правил общения, попытках взлома, злоупотреблении жалобами или использовании сервиса не по назначению.</p>

<h3>8. Ответственность пользователя</h3>
<p>Пользователь самостоятельно отвечает за действия, совершенные через его учетную запись, а также за содержание размещенной информации и отправленных сообщений.</p>
<p>Администрация не несет ответственности за достоверность сведений, которые пользователи указывают в своих профилях, и за действия пользователей за пределами веб-приложения.</p>

<h3>9. Изменение правил</h3>
<p>Администрация веб-приложения может изменять настоящие правила при развитии функционала сервиса, изменении требований безопасности или необходимости уточнения порядка использования приложения.</p>
<p>Актуальная версия правил размещается на странице «Документы сервиса».</p>

<div class="info-note">Продолжая использовать веб-приложение «Мэтч», пользователь подтверждает согласие с настоящими правилами использования.</div>
