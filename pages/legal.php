</div>
</div>

<h3>1. Общие положения</h3>
<p>Настоящая политика конфиденциальности определяет порядок обработки и защиты персональных данных пользователей веб-приложения «Мэтч».</p>
<p>Политика применяется ко всей информации, которую пользователь предоставляет при регистрации, заполнении профиля, использовании функций поиска, общения, подачи жалоб и обращения к администрации сервиса.</p>

<h3>2. Какие данные обрабатываются</h3>
<p>Веб-приложение может обрабатывать следующие данные пользователя:</p>
<ul>
<li>имя пользователя;</li>
<li>никнейм;</li>
<li>адрес электронной почты;</li>
<li>пароль в защищенном виде;</li>
<li>город;</li>
<li>дату рождения или возраст;</li>
<li>цели общения;</li>
<li>интересы;</li>
<li>фотографию профиля;</li>
<li>сообщения, отправленные внутри веб-приложения;</li>
<li>жалобы, решения модерации и обращения пользователя;</li>
<li>технические данные, необходимые для работы сервиса.</li>
</ul>

<h3>3. Цели обработки данных</h3>
<p>Персональные данные обрабатываются для обеспечения работы веб-приложения и предоставления пользователю его функциональных возможностей.</p>
<ul>
<li>создание и использование учетной записи;</li>
<li>авторизация пользователя;</li>
<li>отображение профиля другим участникам;</li>
<li>подбор пользователей по интересам и параметрам поиска;</li>
<li>организация обмена сообщениями;</li>
<li>рассмотрение жалоб и обращений;</li>
<li>обеспечение безопасности веб-приложения;</li>
<li>предотвращение нарушений правил сервиса.</li>
</ul>

<h3>4. Принципы обработки персональных данных</h3>
<p>Обработка персональных данных осуществляется только в объеме, необходимом для работы веб-приложения. Данные используются для заранее определенных целей и не должны применяться способом, несовместимым с назначением сервиса.</p>
<p>Администрация веб-приложения принимает меры для защиты данных от несанкционированного доступа, изменения, удаления, распространения и иных неправомерных действий.</p>

<h3>5. Хранение и защита данных</h3>
<p>Данные пользователей хранятся в базе данных веб-приложения. Пароли не хранятся в открытом виде: для их защиты используется хэширование.</p>
<p>Для защиты данных применяются серверная валидация, разграничение прав доступа, проверка пользовательского ввода, защита от SQL-инъекций и экранирование данных при выводе на страницы веб-приложения.</p>
<p>Доступ к административным и модераторским функциям предоставляется только пользователям с соответствующими ролями.</p>

<h3>6. Сообщения пользователей</h3>
<p>Сообщения, отправленные через веб-приложение, могут храниться в базе данных для обеспечения работы чатов, отображения истории переписки, статуса доставки и рассмотрения жалоб.</p>
<p>Администрация не просматривает личные сообщения без необходимости. Доступ к сообщениям может использоваться при рассмотрении жалобы, выявлении нарушений правил сервиса или обеспечении безопасности пользователей.</p>

<h3>7. Передача данных третьим лицам</h3>
<p>Персональные данные пользователей не передаются третьим лицам без согласия пользователя, за исключением случаев, предусмотренных законодательством, а также случаев, когда передача необходима для защиты прав и безопасности пользователей сервиса.</p>

<h3>8. Права пользователя</h3>
<p>Пользователь имеет право:</p>
<ul>
<li>просматривать и изменять данные своего профиля;</li>
<li>удалять или изменять отдельные сведения, размещенные в профиле;</li>
<li>обратиться к администрации по вопросам обработки данных;</li>
<li>потребовать уточнения, ограничения или удаления своих данных, если это не противоречит требованиям безопасности и техническим возможностям сервиса;</li>
<li>прекратить использование веб-приложения.</li>
</ul>

<h3>9. Файлы cookie и техническая информация</h3>
<p>Веб-приложение может использовать технические данные, необходимые для корректной работы авторизации, сохранения сессии пользователя и обеспечения безопасности.</p>
<p>Такие данные применяются для поддержания работы сервиса и не используются для передачи конфиденциальной информации третьим лицам.</p>

<h3>10. Срок хранения данных</h3>
<p>Данные пользователя хранятся в течение срока использования учетной записи. После удаления аккаунта данные могут быть удалены или обезличены, если их дальнейшее хранение не требуется для обеспечения безопасности, рассмотрения жалоб или выполнения требований законодательства.</p>

<h3>11. Изменение политики конфиденциальности</h3>
<p>Администрация веб-приложения может изменять настоящую политику при изменении функционала сервиса, требований безопасности или порядка обработки данных.</p>
<p>Актуальная версия политики размещается на странице «Документы сервиса».</p>

<div class="info-note">Используя веб-приложение «Мэтч», пользователь подтверждает, что ознакомился с настоящей политикой конфиденциальности.</div>
